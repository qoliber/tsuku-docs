<?php

/**
 * Renders the example outputs of the documentation with the real Tsuku library.
 *
 *   php scripts/render-examples.php            render every example and write its output file
 *   php scripts/render-examples.php --check    write nothing; exit 1 with a diff when an output file
 *                                              is stale or missing, or the pages and examples disagree
 *   php scripts/render-examples.php csv-       only the examples whose path contains "csv-"
 *
 * One directory per example, snippets/examples/<page>/<example>/:
 *
 *   template.<ext>.tsuku  the template, exactly as it is shown on the page
 *   data.php              returns the data array ($data)
 *   example.php           optional: the PHP of the "PHP" tab when the example needs more than the
 *                         default call (registered functions, streaming). It runs with $tsuku,
 *                         $template and $data defined and echoes the output.
 *   output.<ext>          generated by this script; never edited by hand
 *
 * Without example.php the output is `echo $tsuku->process($template, $data);`.
 *
 * Every example renders with a fresh `new Tsuku(StrictnessMode::WARNING)`, timezone UTC. A Tsuku
 * warning (a {variable} that is missing from the data), a PHP warning or an exception fails the run.
 *
 * --check also fails when a page includes a snippet file that does not exist (VitePress would print
 * "Code snippet path not found" and build anyway) and when an example is not used by any page.
 */

declare(strict_types=1);

use Qoliber\Tsuku\StrictnessMode;
use Qoliber\Tsuku\Tsuku;

$root = dirname(__DIR__);
$examplesDir = $root . '/snippets/examples';

require $root . '/vendor/autoload.php';

date_default_timezone_set('UTC');

$args = array_slice($argv, 1);
$check = in_array('--check', $args, true);
$filters = array_values(array_filter($args, static fn (string $a): bool => !str_starts_with($a, '--')));
foreach (array_diff(array_filter($args, static fn (string $a): bool => str_starts_with($a, '--')), ['--check']) as $unknown) {
    fwrite(STDERR, "Unknown option $unknown\n");
    exit(2);
}

$errors = [];
$changed = 0;
$rendered = 0;

foreach (findExamples($examplesDir) as $dir) {
    $id = substr($dir, strlen($examplesDir) + 1);
    if ($filters !== [] && !array_filter($filters, static fn (string $f): bool => str_contains($id, $f))) {
        continue;
    }

    $templates = glob($dir . '/template.*.tsuku') ?: [];
    if (count($templates) !== 1) {
        $errors[] = "$id: expected exactly one template.<ext>.tsuku, found " . count($templates);
        continue;
    }
    if (!is_file($dir . '/data.php')) {
        $errors[] = "$id: data.php is missing";
        continue;
    }
    $ext = substr(basename($templates[0]), strlen('template.'), -strlen('.tsuku'));
    $outputFile = $dir . '/output.' . $ext;
    foreach (glob($dir . '/output.*') ?: [] as $other) {
        if ($other !== $outputFile) {
            $errors[] = "$id: " . basename($other) . ' does not belong to ' . basename($templates[0]);
        }
    }

    try {
        $output = renderExample($dir, $templates[0]);
    } catch (Throwable $e) {
        $errors[] = "$id: " . get_class($e) . ': ' . $e->getMessage();
        continue;
    }
    $rendered++;

    $current = is_file($outputFile) ? file_get_contents($outputFile) : null;
    if ($current === $output) {
        continue;
    }
    $changed++;
    if ($check) {
        $errors[] = $current === null
            ? "$id: output.$ext is missing"
            : "$id: output.$ext is out of date\n" . diff($current, $output, "$id/output.$ext");
        continue;
    }
    file_put_contents($outputFile, $output);
    echo ($current === null ? 'created ' : 'updated ') . "$id/output.$ext\n";
}

if ($filters === []) {
    array_push($errors, ...checkPages($root, $examplesDir));
}

if ($errors !== []) {
    fwrite(STDERR, implode("\n", $errors) . "\n\n" . count($errors) . " problem(s), $rendered example(s) rendered\n");
    exit(1);
}

echo $check
    ? "$rendered example(s) rendered, every output file is up to date\n"
    : "$rendered example(s) rendered, $changed output file(s) written\n";
exit(0);

/** @return list<string> */
function findExamples(string $examplesDir): array
{
    $dirs = [];
    foreach (glob($examplesDir . '/*/*', GLOB_ONLYDIR) ?: [] as $dir) {
        $dirs[] = $dir;
    }
    sort($dirs);

    return $dirs;
}

function renderExample(string $dir, string $templateFile): string
{
    set_error_handler(static function (int $severity, string $message, string $file, int $line): never {
        throw new ErrorException($message, 0, $severity, $file, $line);
    });

    try {
        $template = file_get_contents($templateFile);
        $data = (static fn (): mixed => require $dir . '/data.php')();
        if (!is_array($data)) {
            throw new UnexpectedValueException('data.php must return an array');
        }

        $tsuku = new Tsuku(StrictnessMode::WARNING);
        ob_start();
        try {
            if (is_file($dir . '/example.php')) {
                (static function (Tsuku $tsuku, string $template, array $data, string $file): void {
                    require $file;
                })($tsuku, $template, $data, $dir . '/example.php');
            } else {
                echo $tsuku->process($template, $data);
            }
        } finally {
            $output = ob_get_clean();
        }

        if ($tsuku->hasWarnings()) {
            throw new RuntimeException('Tsuku warnings: ' . implode('; ', $tsuku->getWarnings()));
        }

        return $output;
    } finally {
        restore_error_handler();
    }
}

/**
 * Every snippet a page includes must exist, and every example must be used by a page.
 *
 * @return list<string>
 */
function checkPages(string $root, string $examplesDir): array
{
    $errors = [];
    $used = [];
    $pages = new RecursiveIteratorIterator(new RecursiveCallbackFilterIterator(
        new RecursiveDirectoryIterator($root, FilesystemIterator::SKIP_DOTS),
        static fn (SplFileInfo $f): bool => !in_array($f->getFilename(), ['node_modules', 'vendor', '.vitepress', '.git'], true),
    ));
    foreach ($pages as $page) {
        if ($page->getExtension() !== 'md') {
            continue;
        }
        $rel = substr($page->getPathname(), strlen($root) + 1);
        $md = file_get_contents($page->getPathname());
        // <<< @/snippets/x/y.ext{lang} [Title]
        preg_match_all('#^\s*<<<\s*@/(snippets/[^\s{\[]+)#m', $md, $includes);
        // import x from '../snippets/x/output.html?raw'
        preg_match_all('#from\s+[\'"]([^\'"]*snippets/[^\'"?]+)(?:\?raw)?[\'"]#', $md, $imports);
        $files = $includes[1];
        foreach ($imports[1] as $import) {
            $files[] = substr(realpathOrSelf(dirname($page->getPathname()) . '/' . $import), strlen($root) + 1);
        }
        foreach ($files as $file) {
            if (!is_file($root . '/' . $file)) {
                $errors[] = "$rel: includes $file, which does not exist";
                continue;
            }
            if (str_starts_with($file, 'snippets/examples/')) {
                $used[dirname($root . '/' . $file)] = true;
            }
        }
    }
    foreach (findExamples($examplesDir) as $dir) {
        if (!isset($used[$dir])) {
            $errors[] = substr($dir, strlen($root) + 1) . ': not used by any page';
        }
    }

    return $errors;
}

function realpathOrSelf(string $path): string
{
    return realpath($path) ?: $path;
}

function diff(string $old, string $new, string $label): string
{
    $a = tempnam(sys_get_temp_dir(), 'tsuku-old-');
    $b = tempnam(sys_get_temp_dir(), 'tsuku-new-');
    file_put_contents($a, $old);
    file_put_contents($b, $new);
    $out = shell_exec(sprintf(
        'diff -u --label %s --label %s %s %s 2>&1',
        escapeshellarg("$label (committed)"),
        escapeshellarg("$label (rendered)"),
        escapeshellarg($a),
        escapeshellarg($b),
    ));
    unlink($a);
    unlink($b);

    return rtrim((string) $out);
}
